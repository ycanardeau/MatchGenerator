	[Fact]
	public void Collapses_Enum_Members_That_Share_A_Constant_Value()
	{
		// Friend aliases Internal (same constant value), like Roslyn's Accessibility
		// enum. Emitting both would produce duplicate switch case labels (CS8510) and
		// duplicate parameters, so aliased members collapse to the first declared one.
		var source = """
			using Aigamo.MatchGenerator;

			namespace Test;

			[GenerateMatch]
			public enum Visibility
			{
				None = 0,
				Private = 1,
				Internal = 2,
				Friend = Internal,
				Public = 3
			}
			""";

		var actual = RunGenerator(source);

		var expected = """
			// <auto-generated />
			using System;
			using System.Diagnostics;
			using System.Runtime.CompilerServices;

			namespace Test;

			public static class VisibilityMatchExtensions
			{
				[MethodImpl(MethodImplOptions.AggressiveInlining)]
				public static U Match<U>(
					this Visibility value,
					Func<U> None,
					Func<U> Private,
					Func<U> Internal,
					Func<U> Public
				)
				{
					return value switch
					{
						Visibility.None => None(),
						Visibility.Private => Private(),
						Visibility.Internal => Internal(),
						Visibility.Public => Public(),
						_ => throw new UnreachableException(),
					};
				}
			}

			""";

		Assert.Equal(expected, actual);
	}

