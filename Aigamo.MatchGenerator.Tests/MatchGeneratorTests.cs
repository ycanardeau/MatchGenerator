	private sealed class TestAnalyzerConfigOptions(Dictionary<string, string> options)
		: AnalyzerConfigOptions
	{
		public override bool TryGetValue(string key, out string value) =>
			options.TryGetValue(key, out value!);
	}

	// Mirrors a section-scoped .editorconfig entry (e.g. under [*.cs]): visible per-tree,
	// not via GlobalOptions. This is the shape that exposed the real bug — the generator
	// originally only checked GlobalOptions, so a [*.cs]-scoped setting was silently ignored.
	private sealed class TestAnalyzerConfigOptionsProvider(AnalyzerConfigOptions treeOptions)
		: AnalyzerConfigOptionsProvider
	{
		public override AnalyzerConfigOptions GlobalOptions { get; } =
			new TestAnalyzerConfigOptions([]);

		public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => treeOptions;

		public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => treeOptions;
	}

	private static GeneratorDriverRunResult Run(string source, string? parameterPrefix = null)
	{
		var syntaxTree = CSharpSyntaxTree.ParseText(source);

		var compilation = CSharpCompilation.Create(
			"Tests",
			[syntaxTree],
			[
				MetadataReference.CreateFromFile(typeof(object).Assembly.Location),
				MetadataReference.CreateFromFile(typeof(Func<>).Assembly.Location),
			],
			new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
		);

		var generator = new SourceGenerator();

		GeneratorDriver driver = CSharpGeneratorDriver.Create(generator);
		if (parameterPrefix is not null)
		{
			driver = driver.WithUpdatedAnalyzerConfigOptions(
				new TestAnalyzerConfigOptionsProvider(
					new TestAnalyzerConfigOptions(
						new Dictionary<string, string>
						{
							["matchgenerator_parameter_prefix"] = parameterPrefix,
						}
					)
				)
			);
		}
		driver = driver.RunGenerators(compilation);

		return driver.GetRunResult();
	}

	private static string RunGenerator(string source, string? parameterPrefix = null)
	{
		var result = Run(source, parameterPrefix);
		return result
			.GeneratedTrees.Single(t => t.FilePath.EndsWith("MatchExtensions.g.cs"))
			.GetText()
			.ToString();
	}

	private static List<string> RunGeneratorAll(string source)
	{
		var result = Run(source);
		return [.. result.GeneratedTrees.Select(t => t.GetText().ToString())];
	}

	[Fact]
	public void Generates_Match_Method_For_Enum()
	{
		// Arrange
		var source =
			@"
using Aigamo.MatchGenerator;

namespace Test;

[GenerateMatch]
public enum Gender
{
	Male = 1,
	Female,
}
";

		var actual = RunGenerator(source);

		var expected = """
			// <auto-generated />
			using System;
			using System.Diagnostics;
			using System.Runtime.CompilerServices;

			namespace Test;

			public static class GenderMatchExtensions
			{
				[MethodImpl(MethodImplOptions.AggressiveInlining)]
				public static U Match<U>(
					this Gender value,
					Func<U> Male,
					Func<U> Female
				)
				{
					return value switch
					{
						Gender.Male => Male(),
						Gender.Female => Female(),
						_ => throw new UnreachableException(),
					};
				}
			}

			""";

		// Assert
		Assert.Equal(expected, actual);
	}

